#!/usr/bin/env node
// Interim preview package for Simply.com web hosting (Apache), so normek.dk can show the site
// before the Cloudflare Pages project exists. Not for launch.
//
// Run `npm run build` first, then `npm run package:simply`. It writes dist-simply/, which holds the files
// to upload into the hosting's public_html/ folder. See docs/ops/simply-interim-upload.md.
//
// What changes compared with dist/:
//  - public/_headers does not exist on Apache, so the headers become .htaccess files: the content security
//    policy and the rest. The transport security header stays out, because a browser remembers it for a
//    year and this is a temporary host.
//  - The text that names Cloudflare, Turnstile and Resend is replaced, because on this host the form is not
//    switched on and the text would be untrue.
// It refuses to package a build that is open to search engines.

import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { parseHeadersFile } from "./lib/headers.mjs";

/** Headers that stay out of the .htaccess. HSTS is remembered for a year and cannot be taken back from the server. */
export const SKIPPED_HEADERS = new Set(["strict-transport-security"]);

/**
 * @typedef {import("./lib/headers.mjs").HeaderRule} HeaderRule
 */

/**
 * Apache expands %t, %D and %{NAME}e in a header value, so a value with a percent sign would change on the way out.
 * @param {string} value
 * @returns {string}
 */
function quote(value) {
  if (value.includes("%"))
    throw new Error(`Apache would expand the percent sign in this header value: ${value}`);
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/**
 * The root .htaccess: the headers of the /* rule, the 404 page and a few file types.
 * Every directive sits inside an IfModule, so a module the host lacks never turns the site into an error page.
 * @param {HeaderRule[]} rules
 * @returns {string}
 */
export function rootHtaccess(rules) {
  const everything = rules.find((rule) => rule.pattern === "/*");
  if (!everything) throw new Error("The _headers file has no /* rule.");
  const headerLines = everything.headers
    .filter(([name]) => !SKIPPED_HEADERS.has(name.toLowerCase()))
    .map(([name, value]) => `Header always set ${name} ${quote(value)}`);
  return [
    "# Normek interim preview for Simply.com (Apache). Generated by scripts/build-simply-package.mjs.",
    "# Not for launch. Every directive that needs a module sits inside an IfModule, so a missing module",
    "# never turns the site into an error page.",
    "ErrorDocument 404 /404.html",
    "",
    "<IfModule mod_headers.c>",
    ...headerLines,
    "</IfModule>",
    "",
    "<IfModule mod_mime.c>",
    "AddType font/woff2 .woff2",
    "AddType image/svg+xml .svg",
    "AddType application/manifest+json .webmanifest",
    "</IfModule>",
    "",
  ].join("\n");
}

/**
 * The .htaccess for /_astro/, where every file name carries a hash and so never changes under its address.
 * @param {HeaderRule[]} rules
 * @returns {string}
 */
export function astroHtaccess(rules) {
  const rule = rules.find((r) => r.pattern === "/_astro/*");
  const cache = rule?.headers.find(([name]) => name.toLowerCase() === "cache-control");
  if (!cache) throw new Error("The _headers file has no cache rule for /_astro/*.");
  return [
    "<IfModule mod_headers.c>",
    `Header set Cache-Control ${quote(cache[1])}`,
    "</IfModule>",
    "",
  ].join("\n");
}

/**
 * True when the catch-all rule tells search engines to stay away, which is the only build this package accepts.
 * @param {HeaderRule[]} rules
 * @returns {boolean}
 */
export function isNoindexBuild(rules) {
  const everything = rules.find((rule) => rule.pattern === "/*");
  return (
    everything?.headers.some(
      ([name, value]) => name.toLowerCase() === "x-robots-tag" && /noindex/i.test(value),
    ) ?? false
  );
}

/**
 * The address the pages show for email, read from the built home page so it is never typed in twice.
 * @param {string} html
 * @returns {string}
 */
export function siteEmail(html) {
  const match = html.match(/href="mailto:([^"?]+)["?]/);
  if (!match || !/^[^\s@<>"'&]+@[^\s@<>"'&]+$/.test(match[1])) {
    throw new Error("The home page has no mailto link this script can read.");
  }
  return match[1];
}

/**
 * Matches the text wherever it stands. The build puts a no-break space after one letter words ("a visitor"),
 * so each space of the text also matches U+00A0.
 * @param {string} text
 * @returns {RegExp}
 */
function looseText(text) {
  const escaped = text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(escaped.replace(/ /g, "[ \\u00a0]"), "g");
}

/**
 * Replaces one piece of text, and fails when it is not there exactly once. A build with new copy then
 * stops here, instead of shipping a sentence that names the wrong services.
 * @param {string} text
 * @param {string} from
 * @param {string} to
 * @param {string} where
 * @returns {string}
 */
export function replaceOnce(text, from, to, where) {
  const pattern = looseText(from);
  const found = text.match(pattern)?.length ?? 0;
  if (found !== 1) {
    throw new Error(`Expected exactly one match in ${where}, found ${found}: ${from.slice(0, 70)}`);
  }
  return text.replace(pattern, () => to);
}

/** The sentences of the home page that name the services behind the form, as the build renders them. */
export const DATA_BULLET =
  '<strong class="font-semibold text-fg">The form emails your message to me.</strong> Cloudflare hosts this site and runs the Turnstile check that a visitor is a person. Resend delivers the email. Simply.com hosts my mailbox.';
export const FORM_HELPER =
  'I use your details only to reply to this request. Processors and retention are in the <a class="link" href="/privacy/">privacy notice</a>.';

/**
 * The home page for this host: the form is not switched on, so the text says so and does not name services that are not used.
 * @param {string} html
 * @param {string} email
 * @returns {string}
 */
export function patchHome(html, email) {
  const withBullet = replaceOnce(
    html,
    DATA_BULLET,
    '<strong class="font-semibold text-fg">The contact form is not switched on yet.</strong> Write to me by email. Simply.com hosts this site and my mailbox.',
    "index.html (data bullet)",
  );
  return replaceOnce(
    withBullet,
    FORM_HELPER,
    `The form is not switched on yet. Please email <a class="link" href="mailto:${email}">${email}</a> instead.`,
    "index.html (form helper)",
  );
}

/**
 * The privacy page for this host. The long notice describes the Cloudflare and Resend setup, which this host does
 * not use, so everything between the heading and the end of the page is replaced by a short, true notice.
 * @param {string} html
 * @param {string} email
 * @returns {string}
 */
export function patchPrivacy(html, email) {
  const afterHeading = html.indexOf("</h1>");
  const closing = html.indexOf("</div> </section> </main>");
  if (afterHeading === -1 || closing === -1 || closing < afterHeading) {
    throw new Error("The privacy page does not have the structure this script expects.");
  }
  const notice =
    '<div class="max-w-measure">' +
    '<p class="mb-4">This is a preview of the site. The contact form is not switched on, so use email instead.</p>' +
    '<p class="mb-4">The site sets no cookies and has no analytics. Simply.com hosts it and keeps ordinary server logs, as every web host does. If you email me, I use your address only to answer you.</p>' +
    `<p class="mb-4">Email: <a class="link" href="mailto:${email}">${email}</a>. The full privacy notice will be published before the form goes live.</p>` +
    "</div>";
  return html.slice(0, afterHeading + "</h1>".length) + notice + html.slice(closing);
}

/** A problem the person running the script can fix, such as a missing build. It is reported without a stack trace. */
export class PackageError extends Error {}

/**
 * Builds the package: a copy of the site with .htaccess files for the headers and the interim text.
 * @param {{ distDir?: string, outDir?: string }} [options]
 * @returns {{ outDir: string }}
 */
export function buildSimplyPackage({ distDir = "dist", outDir = "dist-simply" } = {}) {
  if (!existsSync(join(distDir, "index.html")) || !existsSync(join(distDir, "_headers"))) {
    throw new PackageError(`${distDir}/ is missing. Run \`npm run build\` first.`);
  }
  const rules = parseHeadersFile(readFileSync(join(distDir, "_headers"), "utf8"));
  if (!isNoindexBuild(rules)) {
    throw new PackageError(
      "Refusing to package a build that is open to search engines. Build without PUBLIC_INDEXABLE.",
    );
  }
  rmSync(outDir, { recursive: true, force: true });
  cpSync(distDir, outDir, { recursive: true });
  rmSync(join(outDir, "_headers"));
  writeFileSync(join(outDir, ".htaccess"), rootHtaccess(rules));
  writeFileSync(join(outDir, "_astro", ".htaccess"), astroHtaccess(rules));

  const homeFile = join(outDir, "index.html");
  const home = readFileSync(homeFile, "utf8");
  const email = siteEmail(home);
  writeFileSync(homeFile, patchHome(home, email));
  const privacyFile = join(outDir, "privacy", "index.html");
  writeFileSync(privacyFile, patchPrivacy(readFileSync(privacyFile, "utf8"), email));
  return { outDir };
}

function main() {
  try {
    const { outDir } = buildSimplyPackage();
    console.log(
      `Wrote ${outDir}/. Upload its contents into public_html/ (see docs/ops/simply-interim-upload.md).`,
    );
  } catch (error) {
    if (!(error instanceof PackageError)) throw error;
    console.error(error.message);
    process.exit(2);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
